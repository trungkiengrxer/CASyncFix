#!/bin/zsh
# Builds the window-freeze blob and generates ../freeze_blob.inc (bytes + symbol offsets) for the kext.
# The blob is position independent; fz_anchor (thunk.s) must be byte 0. Every __TEXT section after __text is
# copied too, with its relative placement kept, so rip-relative references stay valid.
set -euo pipefail
cd "${0:A:h}"
OUT=${TMPDIR:-/tmp}/casync-freeze-blob; mkdir -p $OUT
CFLAGS=(-arch x86_64 -Oz -ffreestanding -fno-stack-protector -fno-builtin -fno-asynchronous-unwind-tables
        -fno-unwind-tables -fPIC -mno-red-zone -fno-jump-tables -D_FORTIFY_SOURCE=0 -DFZ_PROBE=${FZ_PROBE:-0}
        -Wall -Werror -c)
clang $CFLAGS thunk.s -o $OUT/thunk.o
clang $CFLAGS blob.c -o $OUT/blob.o
ld -arch x86_64 -preload -e _fz_apply_thunk -static -no_uuid $OUT/thunk.o $OUT/blob.o -o $OUT/blob.out

# Undefined symbols mean an external reference the cave cannot satisfy.
if [[ -n "$(nm -u $OUT/blob.out)" ]]; then echo "undefined symbols:"; nm -u $OUT/blob.out; exit 1; fi

# Sections as "segname sectname addr size offset" (otool -l prints them per section, hex addr/size).
SECTS=$(otool -l $OUT/blob.out | awk '/^  sectname/ {s=$2} /^   segname/ {g=$2} /^      addr/ {a=$2} /^      size/ {z=$2}
                                      /^    offset/ {print g, s, a, z, $2}')
# Anything in __DATA (a GOT, a writable global) would not be copied into the cave.
if echo "$SECTS" | awk '$1 != "__TEXT"' | grep -q .; then echo "non-__TEXT sections:"; echo "$SECTS"; exit 1; fi
FIRST=0; FILEOFF=0; LAST=0
while read -r seg sect addr size off; do
  a=$(( addr )); z=$(( size ))
  [[ $sect == __text ]] && { FIRST=$a; FILEOFF=$off; }
  (( a + z > LAST )) && LAST=$(( a + z ))
done <<<"$SECTS"
LEN=$((LAST - FIRST))
dd if=$OUT/blob.out of=$OUT/blob.bin bs=1 skip=$FILEOFF count=$LEN 2>/dev/null

sym() { local a; a=$(nm $OUT/blob.out | awk -v s="$1" '$3==s {print $1}'); [[ -n $a ]] || { echo "missing $1"; exit 1; }; echo $((16#$a - FIRST)); }
{
  echo "// Generated by CASyncFix/freeze_blob/build_blob.sh. Do not edit."
  echo "static const uint8_t fzBlob[] = {"
  xxd -i < $OUT/blob.bin
  echo "};"
  echo "static constexpr size_t fzBlobLen = $LEN;"
  echo "static constexpr size_t fzOffAnchor = $(sym _fz_anchor);"
  echo "static constexpr size_t fzOffThunk = $(sym _fz_apply_thunk);"
  echo "static constexpr size_t fzOffResumeJmp = $(sym _fz_resume_jmp);"
  echo "static constexpr size_t fzOffWrapper = $(sym _fz_prepare_wrapper);"
  echo "static constexpr size_t fzOffConfig = $(sym _fz_config);"
  echo "static constexpr size_t fzOffPresent374 = $(sym _fz_present374_thunk);"
  echo "static constexpr size_t fzOffPresent388 = $(sym _fz_present388_thunk);"
  echo "static constexpr size_t fzOffFlatThunk = $(sym _fz_flat_thunk);"
  echo "static constexpr size_t fzOffFlatResumeJmp = $(sym _fz_flat_resume_jmp);"
  echo "static constexpr size_t fzOffForce = $(sym _fz_force);"
  echo "static constexpr int fzProbe = ${FZ_PROBE:-0};"
} > ../freeze_blob.inc
echo "blob: $LEN bytes -> CASyncFix/freeze_blob.inc ($OUT/blob.out)"
